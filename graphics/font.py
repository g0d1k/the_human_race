class Font:
    """Renders text with per-colour glyph caches (built lazily, then reused)."""

    def __init__(self):
        self._cache = {}

    def glyph(self, ch, color):
        key = (ch, color)
        surf = self._cache.get(key)
        if surf is None:
            rows = GLYPHS.get(ch)
            if rows is None:
                rows = GLYPHS.get(ch.upper(), GLYPHS["?"])
            surf = pygame.Surface((8, 8))
            surf.fill(rgb(BLACK))
            surf.set_colorkey(rgb(BLACK))
            c = rgb(color)
            for y, bits in enumerate(rows):
                for x in range(8):
                    if bits & (0x80 >> x):
                        surf.set_at((x, y), c)
            surf = surf.convert() if pygame.display.get_surface() else surf
            surf.set_colorkey(rgb(BLACK))
            self._cache[key] = surf
        return surf

    def draw(self, surf, text, x, y, color, shadow=None):
        """Draw text at (x, y). A palette-index shadow is drawn 1px down-right."""
        x = int(x)
        y = int(y)
        if shadow is not None:
            cx = x + 1
            for ch in text:
                if ch != " ":
                    surf.blit(self.glyph(ch, shadow), (cx, y + 1))
                cx += 8
        cx = x
        for ch in text:
            if ch != " ":
                surf.blit(self.glyph(ch, color), (cx, y))
            cx += 8

    def draw_center(self, surf, text, y, color, shadow=None, cx=128):
        self.draw(surf, text, cx - len(text) * 4, y, color, shadow)

    def draw_right(self, surf, text, right, y, color, shadow=None):
        self.draw(surf, text, right - len(text) * 8, y, color, shadow)

    def draw_rich(self, surf, segments, x, y, limit=None):
        """Draw a list of (char, color) pairs; stops after `limit` characters."""
        cx = x
        for i, (ch, color) in enumerate(segments):
            if limit is not None and i >= limit:
                break
            if ch != " ":
                surf.blit(self.glyph(ch, color), (cx, y))
            cx += 8


def build_logo_text(font_glyphs, text, scale, colors, shadow_color, outline_color):
    """Build a big pixel-art word from the bitmap font.

    Every font pixel becomes a scale x scale block. `colors` is a list of
    palette indices applied as horizontal gradient bands (top to bottom).
    A dark outline and a drop shadow are added for depth.
    """
    w = len(text) * 8 * scale
    h = 8 * scale
    pad = 2
    surf = pygame.Surface((w + pad * 2 + 2, h + pad * 2 + 2))
    surf.fill(rgb(BLACK))
    # collect solid pixels at the scaled resolution
    solid = set()
    for i, ch in enumerate(text):
        rows = font_glyphs.get(ch, font_glyphs[" "])
        for gy, bits in enumerate(rows):
            for gx in range(8):
                if bits & (0x80 >> gx):
                    bx = (i * 8 + gx) * scale
                    by = gy * scale
                    for yy in range(scale):
                        for xx in range(scale):
                            solid.add((bx + xx, by + yy))
    # shadow
    sc = rgb(shadow_color)
    for (x, y) in solid:
        surf.set_at((x + pad + 2, y + pad + 2), sc)
    # outline
    oc = rgb(outline_color)
    for (x, y) in solid:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            if (x + dx, y + dy) not in solid:
                surf.set_at((x + dx + pad, y + dy + pad), oc)
    # body with gradient bands
    band_h = max(1, h // len(colors))
    for (x, y) in solid:
        ci = min(len(colors) - 1, y // band_h)
        surf.set_at((x + pad, y + pad), rgb(colors[ci]))
    # highlight top edge of each stroke with the brightest colour
    hi = rgb(0x30)
    for (x, y) in solid:
        if (x, y - 1) not in solid and y < h // 2:
            surf.set_at((x + pad, y + pad), hi)
    surf.set_colorkey(rgb(BLACK))
    return surf
