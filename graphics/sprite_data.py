"""Sprite art as text grids.

'.' (or space) is transparent; '1', '2', '3' index into a 3-colour palette of
NES palette indices supplied alongside each grid. Grids defined as a "top"
half are mirrored vertically to form the full sprite (flipping is allowed on
the NES). Ragged rows are padded with transparency on the right.
"""


def mirror(top, share_middle=False):
    """Return top + vertically flipped top (optionally sharing the middle row)."""
    bottom = list(reversed(top[:-1] if share_middle else top))
    return list(top) + bottom


