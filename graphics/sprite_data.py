# ---------------------------------------------------------------------------
# Procedurally produced grids (still text grids, generated deterministically)
# ---------------------------------------------------------------------------
def capsule_grid(width, height):
    """Rounded capsule outline: 3 = outline, 1 = fill."""
    rows = []
    for y in range(height):
        row = []
        for x in range(width):
            edge_y = y == 0 or y == height - 1
            edge_x = x == 0 or x == width - 1
            corner = (x < 2 or x >= width - 2) and (y < 2 or y >= height - 2)
            if corner and (edge_x or edge_y):
                row.append(".")
            elif edge_x or edge_y or (corner and (x in (1, width - 2) and y in (1, height - 2))):
                row.append("3")
            else:
                row.append("1")
        rows.append("".join(row))
    return rows


def explosion_grid(size, radius, ring, seed):
    """A dithered fireball: 3 = hot core, 2 = mid, 1 = outer flame."""
    rows = []
    c = (size - 1) / 2.0
    s = seed
    for y in range(size):
        row = []
        for x in range(size):
            s = (s * 1103515245 + 12345) & 0x7FFFFFFF
            noise = (s >> 16) % 100
            d = ((x - c) ** 2 + (y - c) ** 2) ** 0.5
            ch = "."
            if d <= radius:
                if d < radius - ring * 2:
                    ch = "3" if noise > 15 else "2"
                elif d < radius - ring:
                    ch = "2" if noise > 20 else "1"
                else:
                    ch = "1" if noise > 30 else "."
            row.append(ch)
        rows.append("".join(row))
    return rows


def hollow_explosion_grid(size, radius, thickness, seed):
    """Late-stage smoke ring with holes."""
    rows = []
    c = (size - 1) / 2.0
    s = seed
    for y in range(size):
        row = []
        for x in range(size):
            s = (s * 1103515245 + 12345) & 0x7FFFFFFF
            noise = (s >> 16) % 100
            d = ((x - c) ** 2 + (y - c) ** 2) ** 0.5
            ch = "."
            if radius - thickness <= d <= radius and noise > 35:
                ch = "1" if noise < 70 else "2"
            row.append(ch)
        rows.append("".join(row))
    return rows
